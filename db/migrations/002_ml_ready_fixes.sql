BEGIN;

-- 1. CATEGORIES: your 8 core groups --------------------------------------------------------------------
ALTER TABLE service_categories
    ADD COLUMN IF NOT EXISTS slug    VARCHAR(60),
    ADD COLUMN IF NOT EXISTS name_az VARCHAR(120),
    ADD COLUMN IF NOT EXISTS name_ru VARCHAR(120);

UPDATE service_categories SET category_name = 'Electrical Services'    WHERE category_name = 'Electrical';
UPDATE service_categories SET category_name = 'Painting & Renovation'  WHERE category_name = 'Painting';
UPDATE service_categories SET is_active = FALSE                        WHERE category_name = 'Carpentry'; -- not a core group; row kept for FKs
UPDATE service_categories SET slug = CASE category_name
        WHEN 'Plumbing' THEN 'plumbing'
        WHEN 'Electrical Services' THEN 'electrical'
        WHEN 'Appliance Repair' THEN 'appliance_repair'
        WHEN 'Painting & Renovation' THEN 'painting_renovation'
        WHEN 'Carpentry' THEN 'carpentry' END
 WHERE slug IS NULL AND category_name IN ('Plumbing','Electrical Services','Appliance Repair','Painting & Renovation','Carpentry');

CREATE UNIQUE INDEX IF NOT EXISTS uq_service_categories_slug ON service_categories(slug);
ALTER TABLE service_categories DROP CONSTRAINT IF EXISTS chk_active_category_has_slug;
ALTER TABLE service_categories ADD  CONSTRAINT chk_active_category_has_slug CHECK (NOT is_active OR slug IS NOT NULL);

-- 2. SKILL CODES + PROBLEM TYPES (the vocabulary the NLP model predicts) -----------------------------------
ALTER TABLE skills
    ADD COLUMN IF NOT EXISTS skill_code    VARCHAR(60),
    ADD COLUMN IF NOT EXISTS skill_name_az VARCHAR(160);
CREATE UNIQUE INDEX IF NOT EXISTS uq_skills_code ON skills(skill_code);

CREATE TABLE IF NOT EXISTS problem_types (
    problem_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT NOT NULL REFERENCES service_categories(category_id) ON DELETE RESTRICT,
    code            VARCHAR(60) NOT NULL UNIQUE,
    name_en         VARCHAR(160) NOT NULL,
    name_az         VARCHAR(160) NOT NULL,
    risk_flags      TEXT[] NOT NULL DEFAULT '{}',
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (problem_type_id, category_id)           -- lets listings prove category/problem consistency (below)
);
CREATE TABLE IF NOT EXISTS problem_type_skills (
    problem_type_id BIGINT NOT NULL REFERENCES problem_types(problem_type_id) ON DELETE CASCADE,
    skill_id        BIGINT NOT NULL REFERENCES skills(skill_id) ON DELETE RESTRICT,
    PRIMARY KEY (problem_type_id, skill_id)
);

-- Confirmed problem type of a listing (set by the customer's guided form or an admin). This is the TRAINING LABEL;
-- model guesses go to ml_predictions. The composite FK guarantees the problem type belongs to the listing's category.
ALTER TABLE listings ADD COLUMN IF NOT EXISTS problem_type_id BIGINT;
ALTER TABLE listings DROP CONSTRAINT IF EXISTS fk_listing_problem_type_category;
ALTER TABLE listings ADD  CONSTRAINT fk_listing_problem_type_category
    FOREIGN KEY (problem_type_id, category_id) REFERENCES problem_types(problem_type_id, category_id) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_listings_problem_type ON listings(problem_type_id) WHERE problem_type_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_listings_problem_details ON listings USING GIN (problem_details jsonb_path_ops);

-- 3. PHONE NUMBERS: one person = one account, whatever the formatting ----------------------------------------
-- Reproduced: '+994555555555', '+994 55 555 55 55', '0555555555', '055-555-55-55' created 4 accounts.
CREATE OR REPLACE FUNCTION normalize_phone(p TEXT) RETURNS TEXT LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    d    TEXT := regexp_replace(COALESCE(p, ''), '[^0-9]', '', 'g');
    plus BOOLEAN := left(btrim(COALESCE(p, '')), 1) = '+';
BEGIN
    IF d = '' THEN RETURN p; END IF;
    IF plus THEN RETURN '+' || d; END IF;
    IF left(d, 2) = '00' THEN RETURN '+' || substr(d, 3); END IF;
    IF left(d, 3) = '994' AND length(d) = 12 THEN RETURN '+' || d; END IF;
    IF left(d, 1) = '0' AND length(d) = 10 THEN RETURN '+994' || substr(d, 2); END IF;
    IF length(d) = 9 THEN RETURN '+994' || d; END IF;
    RETURN p;   -- unknown shape: leave unchanged so the E.164 CHECK rejects it
END $$;

CREATE OR REPLACE FUNCTION trg_normalize_phone() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.phone_number := normalize_phone(NEW.phone_number); RETURN NEW; END $$;
DROP TRIGGER IF EXISTS trg_users_normalize_phone ON users;
CREATE TRIGGER trg_users_normalize_phone BEFORE INSERT OR UPDATE OF phone_number ON users
    FOR EACH ROW EXECUTE FUNCTION trg_normalize_phone();
UPDATE users SET phone_number = normalize_phone(phone_number) WHERE phone_number IS DISTINCT FROM normalize_phone(phone_number);
ALTER TABLE users DROP CONSTRAINT IF EXISTS chk_users_phone_e164;
ALTER TABLE users ADD  CONSTRAINT chk_users_phone_e164 CHECK (phone_number ~ '^\+[1-9][0-9]{7,14}$');

-- 4. SERVICE AREAS: UNIQUE(master_id, city, district) treats NULL districts as distinct ------------------------
DELETE FROM master_service_areas a USING master_service_areas b
 WHERE a.district IS NULL AND b.district IS NULL AND a.master_id = b.master_id AND a.city = b.city
   AND a.service_area_id > b.service_area_id;
CREATE UNIQUE INDEX IF NOT EXISTS uq_master_service_area_no_district ON master_service_areas (master_id, city) WHERE district IS NULL;

-- 5. OFFERS / JOBS / REVIEWS: integrity the rating features depend on -------------------------------------
-- 5a. an offer's total must equal its parts (NOT VALID = enforced for new rows; run VALIDATE once old rows are clean)
ALTER TABLE master_offers DROP CONSTRAINT IF EXISTS chk_offer_total_matches_parts;
ALTER TABLE master_offers ADD  CONSTRAINT chk_offer_total_matches_parts CHECK (
    price_type = 'Hourly' OR labor_cost IS NULL OR materials_cost IS NULL
    OR proposed_total = labor_cost + materials_cost + travel_cost + other_cost) NOT VALID;

-- 5b. nobody can do business with themselves (a user may legitimately hold both Customer and Master roles)
ALTER TABLE jobs DROP CONSTRAINT IF EXISTS chk_job_parties_differ;
ALTER TABLE jobs ADD  CONSTRAINT chk_job_parties_differ CHECK (customer_id <> master_id);

CREATE OR REPLACE FUNCTION trg_offer_not_on_own_listing() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM listings l WHERE l.listing_id = NEW.listing_id AND l.customer_id = NEW.master_id) THEN
        RAISE EXCEPTION 'a master cannot make an offer on their own listing' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_master_offers_not_own ON master_offers;
CREATE TRIGGER trg_master_offers_not_own BEFORE INSERT OR UPDATE OF listing_id, master_id ON master_offers
    FOR EACH ROW EXECUTE FUNCTION trg_offer_not_on_own_listing();

-- 5c. reviews only for completed jobs (reviews are the label for "was this master good?")
CREATE OR REPLACE FUNCTION trg_review_only_completed_job() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM jobs j WHERE j.job_id = NEW.job_id AND j.status = 'Completed') THEN
        RAISE EXCEPTION 'reviews are only allowed for Completed jobs' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_reviews_completed_only ON reviews;
CREATE TRIGGER trg_reviews_completed_only BEFORE INSERT ON reviews
    FOR EACH ROW EXECUTE FUNCTION trg_review_only_completed_job();

-- 5d. a profile requires the matching role (checked at COMMIT, so signup order inside a transaction does not matter)
CREATE OR REPLACE FUNCTION trg_profile_requires_role() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE need_role TEXT := CASE TG_TABLE_NAME WHEN 'master_profiles' THEN 'Master' ELSE 'Customer' END;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = NEW.user_id AND ur.role = need_role) THEN
        RAISE EXCEPTION 'user % has no % role', NEW.user_id, need_role USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS trg_master_profile_requires_role ON master_profiles;
CREATE CONSTRAINT TRIGGER trg_master_profile_requires_role AFTER INSERT ON master_profiles
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trg_profile_requires_role();
DROP TRIGGER IF EXISTS trg_customer_profile_requires_role ON customer_profiles;
CREATE CONSTRAINT TRIGGER trg_customer_profile_requires_role AFTER INSERT ON customer_profiles
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trg_profile_requires_role();

-- 6. ML: photo (YOLO) predictions need somewhere to live ----------------------------------------------------
ALTER TABLE ml_predictions DROP CONSTRAINT IF EXISTS ml_predictions_entity_type_check;
ALTER TABLE ml_predictions ADD  CONSTRAINT ml_predictions_entity_type_check
    CHECK (entity_type IN ('Listing', 'Master', 'Offer', 'User', 'Attachment', 'Job'));

-- 7. PRIVACY: consent + a PII-free training view ---------------------------------------------------------------
-- Check with a lawyer what Azerbaijani personal-data rules require before training on customer content.
ALTER TABLE customer_profiles
    ADD COLUMN IF NOT EXISTS ml_training_consent    BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS ml_training_consent_at TIMESTAMPTZ;
ALTER TABLE customer_profiles DROP CONSTRAINT IF EXISTS chk_consent_has_timestamp;
ALTER TABLE customer_profiles ADD  CONSTRAINT chk_consent_has_timestamp CHECK (NOT ml_training_consent OR ml_training_consent_at IS NOT NULL);

ALTER TABLE listing_attachments
    ADD COLUMN IF NOT EXISTS sha256        CHAR(64),
    ADD COLUMN IF NOT EXISTS exif_stripped BOOLEAN NOT NULL DEFAULT FALSE;   -- photo EXIF can contain GPS coordinates
CREATE UNIQUE INDEX IF NOT EXISTS uq_attachment_listing_hash ON listing_attachments(listing_id, sha256) WHERE sha256 IS NOT NULL;

-- Training export: only consenting customers, no name / phone / e-mail / exact address / coordinates,
-- only photos whose EXIF has been stripped. Free text can still contain a phone number: redact in Python too.
CREATE OR REPLACE VIEW ml_training_listings AS
SELECT l.listing_id, c.slug AS category_slug, pt.code AS problem_type_code,
       l.title, l.description, l.problem_details, l.urgency, l.city, l.district,
       l.budget_min, l.budget_max, l.budget_type, l.created_at,
       (SELECT array_agg(a.file_url ORDER BY a.created_at)
          FROM listing_attachments a
         WHERE a.listing_id = l.listing_id AND a.mime_type LIKE 'image/%' AND a.exif_stripped) AS photo_urls
  FROM listings l
  JOIN service_categories c ON c.category_id = l.category_id
  JOIN customer_profiles cp ON cp.user_id = l.customer_id
  LEFT JOIN problem_types pt ON pt.problem_type_id = l.problem_type_id
 WHERE cp.ml_training_consent AND l.status <> 'Draft';

COMMIT;

